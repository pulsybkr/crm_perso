'use strict';

// Copie ponctuelle depuis SQLite. La destination doit être vide ; aucune table
// existante n'est supprimée ou remplacée. Les deux lectures sont transactionnelles.
require('dotenv').config({ path: '.env.local', quiet: true });
const path = require('node:path');
const fs = require('node:fs');
const Database = require('better-sqlite3');
const { Client } = require('pg');
const { SCHEMA } = require('../lib/schema.js');

const tables = ['platforms', 'actions', 'meta', 'users', 'user_platforms', 'sessions', 'accounts', 'snapshots'];
const source = process.env.SUIVI_DB || path.join(process.cwd(), 'data', 'suivi-brazza.db');
const ident = name => '"' + name.replace(/"/g, '""') + '"';

async function main() {
  if (!process.env.DATABASE_URL) throw new Error('DATABASE_URL est absent.');
  if (!fs.existsSync(source)) throw new Error('Base SQLite introuvable.');
  const sqlite = new Database(source, { readonly: true, fileMustExist: true });
  const pg = new Client({ connectionString: process.env.DATABASE_URL });
  let connected = false;
  try {
    sqlite.exec('BEGIN');
    await pg.connect(); connected = true;
    await pg.query('BEGIN');
    await pg.query("SELECT pg_advisory_xact_lock(hashtext('suivi-brazza-migration'))");
    const existing = await pg.query("SELECT tablename FROM pg_tables WHERE schemaname = current_schema()");
    if (existing.rowCount) throw new Error('La destination contient déjà des tables : migration annulée.');

    const schema = SCHEMA
      .replace(/INTEGER PRIMARY KEY AUTOINCREMENT/g, 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
      .replace(/datetime\('now'\)/g, "to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')");
    await pg.query(schema);

    for (const table of tables) {
      const rows = sqlite.prepare(`SELECT * FROM ${ident(table)}`).all();
      for (const row of rows) {
        const columns = Object.keys(row);
        const placeholders = columns.map((_, i) => `$${i + 1}`);
        await pg.query(`INSERT INTO ${ident(table)} (${columns.map(ident).join(', ')}) VALUES (${placeholders.join(', ')})`, columns.map(column => row[column]));
      }
      const result = await pg.query(`SELECT COUNT(*)::integer AS n FROM ${ident(table)}`);
      if (result.rows[0].n !== rows.length) throw new Error(`Comptage incorrect pour ${table}.`);
      console.log(`${table}: ${rows.length} lignes vérifiées`);
    }
    await pg.query("SELECT setval(pg_get_serial_sequence('snapshots', 'id'), COALESCE((SELECT MAX(id) FROM snapshots), 1), EXISTS (SELECT 1 FROM snapshots))");
    await pg.query('COMMIT');
    sqlite.exec('COMMIT');
    console.log('Migration terminée. La base SQLite originale est conservée.');
  } catch (error) {
    if (connected) await pg.query('ROLLBACK').catch(() => {});
    try { sqlite.exec('ROLLBACK'); } catch {}
    throw error;
  } finally {
    sqlite.close();
    if (connected) await pg.end();
  }
}

main().catch(error => { console.error('Migration annulée :', error.message); process.exitCode = 1; });
